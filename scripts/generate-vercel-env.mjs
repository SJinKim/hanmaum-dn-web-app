import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const outputPath = resolve(root, 'src/environments/environment.prod.ts');

function clean(value) {
  return typeof value === 'string' && value.trim().length > 0 ? value.trim() : undefined;
}

function normalizeHttpsHost(value) {
  const raw = clean(value);
  if (!raw) return undefined;
  return raw.startsWith('http://') || raw.startsWith('https://') ? raw.replace(/\/$/, '') : `https://${raw.replace(/\/$/, '')}`;
}

// Hosts and realms only prod may use. A preview build that resolves to one fails (#127).
const PROD_API_HOSTS = ['api.graceops.de'];
const PROD_REALM_SUFFIX = '-prod';

// Preview reads the STAGING_* variables first, so a value that Vercel shares with
// production (API_DOMAIN, KEYCLOAK_REALM, ...) cannot pull a preview onto prod.
function pick(env, name) {
  return env.VERCEL_ENV === 'preview' ? clean(env[`STAGING_${name}`]) ?? clean(env[name]) : clean(env[name]);
}

function normalizeApiBaseUrl(env) {
  const explicit = normalizeHttpsHost(pick(env, 'API_BASE_URL'));
  if (explicit) return explicit;

  const domain = pick(env, 'API_DOMAIN') ?? clean(env.STAGING_API_DOMAIN);
  const base = normalizeHttpsHost(domain);
  return base ? `${base}/api` : '/api';
}

function normalizeKeycloakUrl(env) {
  const explicit = normalizeHttpsHost(pick(env, 'KEYCLOAK_URL'));
  if (explicit) return explicit;

  const issuer = pick(env, 'APP_SECURITY_KEYCLOAK_PUBLIC_ISSUER');
  if (issuer) {
    const match = issuer.match(/^(https?:\/\/[^/]+)\/realms\//);
    if (match?.[1]) return match[1].replace(/\/$/, '');
  }

  return normalizeHttpsHost(pick(env, 'AUTH_DOMAIN')) ?? 'http://localhost:8091';
}

function normalizeRealm(env) {
  const explicit = pick(env, 'KEYCLOAK_REALM');
  if (explicit) return explicit;

  const issuer = pick(env, 'APP_SECURITY_KEYCLOAK_PUBLIC_ISSUER');
  if (issuer) {
    const match = issuer.match(/\/realms\/([^/?#]+)/);
    if (match?.[1]) return decodeURIComponent(match[1]);
  }

  return 'hanmaum';
}

function hostOf(url) {
  try {
    return new URL(url).hostname;
  } catch {
    return undefined;
  }
}

export function resolveEnvironment(env) {
  const environment = {
    production: true,
    apiBaseUrl: normalizeApiBaseUrl(env),
    keycloak: {
      url: normalizeKeycloakUrl(env),
      realm: normalizeRealm(env),
      clientId: pick(env, 'KEYCLOAK_CLIENT_ID') ?? 'hanmaum-dashboard',
    },
  };

  if (env.VERCEL_ENV === 'preview') {
    if (PROD_API_HOSTS.includes(hostOf(environment.apiBaseUrl))) {
      throw new Error(`Preview build points at the prod API (${environment.apiBaseUrl}). Set STAGING_API_DOMAIN.`);
    }
    if (environment.keycloak.realm.endsWith(PROD_REALM_SUFFIX)) {
      throw new Error(`Preview build points at the prod realm (${environment.keycloak.realm}). Set STAGING_KEYCLOAK_REALM.`);
    }
  }

  return environment;
}

function main() {
  const environment = resolveEnvironment(process.env);
  const content = `// Auto-generated by scripts/generate-vercel-env.mjs during production builds.\n// Do not edit deployed values here; set Vercel Environment Variables instead.\nexport const environment = ${JSON.stringify(environment, null, 2)};\n`;

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, content);

  console.log('Generated src/environments/environment.prod.ts');
  console.log(JSON.stringify(environment, null, 2));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}

#!/usr/bin/env node
// Builds src/app/core/data/de-plz.data.ts — PLZ → Ort for the 새가족 등록 form (#174).
//
// Source: GeoNames (https://www.geonames.org), CC BY 4.0. Two exports:
//   export/zip/DE.zip   postal codes, but also every Großkunde (companies, Finanzämter …)
//   export/dump/DE.zip  all features; its populated places tell real Orte from Großkunden
// .github/workflows/plz-data.yml runs this every January and opens a PR against dev.
// By hand:
//   curl -sSfL -o zip.zip https://download.geonames.org/export/zip/DE.zip && unzip -p zip.zip DE.txt > postal.txt
//   curl -sSfL -o dump.zip https://download.geonames.org/export/dump/DE.zip && unzip -p dump.zip DE.txt > places.txt
//   node scripts/build-plz-data.mjs postal.txt places.txt
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('../src/app/core/data/de-plz.data.ts', import.meta.url);

const [postalFile, placesFile] = process.argv.slice(2);
if (!postalFile || !placesFile) {
  console.error('usage: node scripts/build-plz-data.mjs <postal DE.txt> <dump DE.txt>');
  process.exit(1);
}

const tsv = file => readFileSync(file, 'utf8').split('\n').map(line => line.split('\t'));

// Feature class P = populated place, A = administrative area (Gemeinde, Stadt).
// Großkunden also file under bare words like "Stadt" (Stadtverwaltung) or "Universität",
// and districts are no Ort to write on a letter.
const NOT_AN_ORT = /^(Stadt|Universität|Gemeinde|Klinikum)$|^(Landkreis|Kreis|Regierungsbezirk|Bezirk) /;
const places = new Set(tsv(placesFile).filter(c => c[6] === 'P' || c[6] === 'A').map(c => c[1]));
const isPlace = name =>
  !NOT_AN_ORT.test(name) && (places.has(name) || places.has(name.replace(/\s*\(.*\)$/, '')));

const rows = tsv(postalFile)
  .filter(c => /^\d{5}$/.test(c[1] ?? '') && c[2]?.trim())
  .map(c => ({ plz: c[1], name: c[2].trim() }));

// "Dresden Friedrichstadt" or "Hamburg Commercial Bank AG" → the Ort in front.
// Only an Ort the postal list itself carries counts as the head.
const postalPlaces = new Set(rows.map(r => r.name).filter(isPlace));
function toPlace(name) {
  if (isPlace(name)) return name;
  const words = name.split(' ');
  for (let k = words.length - 1; k >= 1; k--) {
    const head = words.slice(0, k).join(' ');
    if (postalPlaces.has(head)) return head;
  }
  return null;
}

const byPlz = new Map();
for (const { plz, name } of rows) {
  const place = toPlace(name);
  if (!place) continue;
  if (!byPlz.has(plz)) byPlz.set(plz, new Set());
  byPlz.get(plz).add(place);
}

// One line per PLZ: "<distance to the previous PLZ>\t<Ort>|<Ort>…", about 64 KB over the wire (Brotli).
const lines = [];
let previous = 0;
for (const plz of [...byPlz.keys()].sort()) {
  const names = [...byPlz.get(plz)].sort((a, b) => a.localeCompare(b, 'de'));
  lines.push(`${Number(plz) - previous}\t${names.join('|')}`);
  previous = Number(plz);
}

writeFileSync(OUT, `// Generated by scripts/build-plz-data.mjs — do not edit.
// Postal codes and places: GeoNames (https://www.geonames.org), CC BY 4.0.
export const DE_PLZ = ${JSON.stringify(lines.join('\n'))};
`);
console.log(`${lines.length} PLZ → ${OUT.pathname}`);
